const assert = require("node:assert/strict");
const { DatabaseSync } = require("node:sqlite");
const { normalizeIp, getClientIp, resolveIpLocation, ensureIpLocationTable, recordIpLocation } = require("../src/ip-location");
const { adminActivity } = require("../src/admin-monitor");
const request = (peer, forwarded) => ({ socket: { remoteAddress: peer }, headers: { "x-forwarded-for": forwarded } });
assert.equal(normalizeIp("::ffff:8.8.8.8"), "8.8.8.8");
assert.equal(normalizeIp("[2001:4860:4860::8888]"), "2001:4860:4860::8888");
assert.equal(normalizeIp("1.2.3"), null);
assert.equal(normalizeIp("<script>"), null);
assert.equal(getClientIp(request("8.8.8.8", "1.1.1.1"), ""), "8.8.8.8");
assert.equal(getClientIp(request("8.8.8.8", "1.1.1.1"), "loopback"), "8.8.8.8");
assert.equal(getClientIp(request("127.0.0.1", "1.1.1.1"), "loopback"), "1.1.1.1");
assert.equal(getClientIp(request("::ffff:127.0.0.1", "1.1.1.1, 10.0.0.2"), "loopback,10.0.0.0/8"), "1.1.1.1");
assert.equal(getClientIp(request("127.0.0.1", "spoofed, 1.1.1.1"), "loopback"), "1.1.1.1");
assert.equal(getClientIp(request("127.0.0.1", "1.1.1.1, invalid"), "loopback"), "127.0.0.1");
assert.equal(getClientIp(request("127.0.0.1", "1.1.1.1"), "invalid-network"), "127.0.0.1");
const unexpectedLookup = () => { throw new Error("Non-public addresses must not reach the lookup provider"); };
for (const ip of ["127.0.0.1", "::1", "10.0.0.1", "192.168.2.1", "172.16.0.1", "169.254.2.1", "100.64.0.1", "fc00::1", "fe80::1"]) assert.equal(resolveIpLocation(ip, unexpectedLookup).status, "local");
for (const ip of ["192.0.2.1", "198.51.100.1", "203.0.113.1", "224.0.0.1"]) assert.equal(resolveIpLocation(ip, unexpectedLookup).status, "reserved");
let lookups = 0;
const lookup = () => { lookups++; return { country: "IN", region: "KA", city: "Bengaluru", ll: [12.9716, 77.5946] }; };
const location = resolveIpLocation("8.8.8.8", lookup);
assert.equal(location.location, "Bengaluru, India");
assert(Math.abs(location.mapX - 67.83821633089815) < .001);
assert(location.mapY > 40 && location.mapY < 43);
assert.equal(resolveIpLocation("8.8.8.8", () => null).status, "unavailable");
assert.equal(resolveIpLocation("8.8.8.8", () => { throw new Error("Unavailable provider"); }).status, "unavailable");
assert.equal(resolveIpLocation("8.8.8.8", () => ({ country: "IN", ll: [999, 999] })).mapX, null);
assert.equal(resolveIpLocation("8.8.8.8", () => ({ country: "IN", ll: [0, 0] })).mapX, null);
assert.equal(resolveIpLocation("8.8.8.8").status, "resolved", "The installed offline dataset must actually resolve a public IP.");
const db = new DatabaseSync(":memory:");
try {
  ensureIpLocationTable(db);
  lookups = 0;
  assert.equal(recordIpLocation(db, "8.8.8.8", lookup).city, "Bengaluru");
  assert.equal(recordIpLocation(db, "::ffff:8.8.8.8", lookup).city, "Bengaluru");
  assert.equal(lookups, 1);
  db.exec("UPDATE ip_geolocations SET updated_at = '2020-01-01T00:00:00Z'");
  recordIpLocation(db, "8.8.8.8", lookup);
  assert.equal(lookups, 2);
  db.exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,name TEXT,email TEXT);
    CREATE TABLE login_history(id INTEGER PRIMARY KEY,user_id INTEGER,email TEXT,action TEXT,success INTEGER,
      device TEXT,browser TEXT,ip_address TEXT,timestamp TEXT,location_json TEXT);
    INSERT INTO users VALUES(1,'Fixture','fixture@example.test');`);
  const insert = db.prepare("INSERT INTO login_history(user_id,email,action,success,device,browser,ip_address,timestamp,location_json) VALUES(?,?,?,?,?,?,?,?,?)");
  const event = (ip, action, success, timestamp, json = null) => insert.run(1, "fixture@example.test", action, success, "Windows", "Chrome", ip, timestamp, json);
  event("8.8.8.8", "Login", 1, "2026-10-07T08:00:00Z");
  event("::ffff:8.8.8.8", "Login", 1, "2026-10-07T09:00:00Z");
  event("127.0.0.1", "Login", 1, "2026-10-07T10:00:00Z");
  event("192.0.2.1", "Login", 1, "2026-10-07T11:00:00Z");
  event("8.8.8.8", "Logout", 1, "2026-10-07T12:00:00Z");
  event("8.8.8.8", "Failed Login", 0, "2026-10-07T12:10:00Z", JSON.stringify({ ...location, location: "Earlier location" }));
  event("8.8.8.8", "Failed Login", 0, "2026-10-07T12:15:00Z", JSON.stringify(location));
  event("8.8.8.8", "Login", 1, "2026-10-06T08:00:00Z");
  const result = adminActivity(db, 1, new Date("2026-10-07T13:00:00Z"));
  assert.equal(result.locations.length, 1);
  assert.equal(result.locations[0].logins, 2);
  assert.equal(result.locations[0].users, 1);
  assert.equal(result.locations[0].location, "Bengaluru, India");
  assert.equal(result.locationSummary.totalLogins, 4);
  assert.equal(result.locationSummary.locatedLogins, 2);
  assert.equal(result.locationSummary.localNetworkLogins, 1);
  assert.equal(result.locationSummary.reservedIpLogins, 1);
  assert.equal(result.failedAttempts.length, 1);
  assert.equal(result.failedAttempts[0].attempts, 2);
  assert.equal(result.failedAttempts[0].location, "Bengaluru, India");
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM login_history WHERE location_json IS NULL").get().count, 1);
  assert.equal(db.prepare("SELECT location_json FROM login_history WHERE timestamp='2026-10-07T12:10:00Z'").get().location_json, JSON.stringify({ ...location, location: "Earlier location" }));
  const repeat = adminActivity(db, 1, new Date("2026-10-07T13:00:00Z"));
  assert.deepEqual(repeat.locations, result.locations);
  assert.equal(adminActivity(db, 7, new Date("2026-10-07T13:00:00Z")).locations[0].logins, 3);
} finally { db.close(); }
console.log("IP location tests passed: IPv4/IPv6, trusted proxies, spoofing, private/reserved addresses, offline lookup, caching, map projection, persisted history, backfill, ranges, login-only totals, and failure grouping.");
